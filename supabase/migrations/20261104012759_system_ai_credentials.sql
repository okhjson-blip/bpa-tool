begin;

-- 시스템 관리자가 등록·우선순위로 관리하는 전역 AI API 자격증명.
-- 협력사와 무관하게 모든 AI 분석 요청이 이 풀을 사용한다.
create table if not exists public.system_ai_credentials (
  id bigint generated by default as identity primary key,
  provider text not null check (provider in ('gemini', 'chatgpt', 'claude', 'openrouter', 'github')),
  display_name text,
  encrypted_key text not null,
  encryption_iv text not null,
  auth_tag text not null,
  key_last_four text,
  model_override text,
  tested_model text,
  tested_at timestamptz,
  priority integer not null default 100 check (priority >= 1),
  status text not null default 'active' check (status in ('active', 'disabled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz
);

create index if not exists idx_system_ai_credentials_priority
  on public.system_ai_credentials(status, priority, id);

alter table public.system_ai_credentials enable row level security;

revoke all on public.system_ai_credentials from anon, authenticated;
grant select, insert, update, delete on public.system_ai_credentials to service_role;
grant usage, select on all sequences in schema public to service_role;

-- 프로젝트 AI 엔진은 시스템 풀 우선순위에 따라 동적으로 선택되므로
-- companies.default_ai_provider 제약을 새 프로바이더까지 확장한다(레거시 호환).
alter table public.companies
  drop constraint if exists companies_default_ai_provider_check;

alter table public.companies
  add constraint companies_default_ai_provider_check
  check (
    default_ai_provider is null
    or default_ai_provider in ('gemini', 'chatgpt', 'claude', 'openrouter', 'github')
  );

commit;
